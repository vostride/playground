import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { writeFile } from 'node:fs/promises';
import { ProductArt } from '../apps/shop/src/ProductArt';
import { products } from '../packages/core/src/shop';
const art = Object.fromEntries(
  products.slice(0, 12).map((p) => [
    p.art,
    renderToStaticMarkup(<ProductArt art={p.art} color={p.color} />)
      .replace(/<filter[\s\S]*?<\/filter>/g, '')
      .replace(/ filter="[^"]*"/g, ''),
  ]),
);
await writeFile(
  'apps/mobile/src/screens/ShopArt.ts',
  `// Generated by scripts/export-shop-art.tsx from original Komazon artwork.\nexport const shopArt: Record<string,string> = ${JSON.stringify(art, null, 2)};\n`,
);
